#!/usr/bin/env python3
"""Generate checked Rust decoders from the packed telemetry field tables.

No network or third-party parser implementation is used. Run from any directory.
Optional packet IDs limit generation during a red-green development cycle.
"""
import json
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]
TABLES = json.loads(Path(__file__).with_name('packet_tables.json').read_text())
PACKETS = ['Motion', 'Session', 'Lap', 'Event', 'Participants', 'CarSetup',
           'CarTelemetry', 'CarStatus', 'FinalClassification', 'LobbyInfo',
           'CarDamage', 'SessionHistory', 'TyreSets', 'MotionEx', 'TimeTrial',
           'LapPositions', 'CarTelemetry2']
PRIMITIVES = {'u8': 1, 'i8': 1, 'u16': 2, 'i16': 2, 'u32': 4, 'u64': 8,
              'f32': 4, 'f64': 8}
ENABLED = set(map(int, sys.argv[1:])) if len(sys.argv) > 1 else set(range(17))


def fields(kind):
    result = {}
    for schema in TABLES.values():
        for field in schema.get(kind, []):
            if field['name'] != 'header':
                result.setdefault(field['name'], []).append(field)
    return result


def size(kind, dims, schema):
    if dims:
        return dims[0] * size(kind, dims[1:], schema)
    if kind in PRIMITIVES:
        return PRIMITIVES[kind]
    return sum(size(f['type'], f['dims'], schema) for f in schema[kind])


needed = {'PacketHeader'}
def require(kind):
    if kind in PRIMITIVES or kind in needed:
        return
    needed.add(kind)
    for versions in fields(kind).values():
        for field in versions:
            require(field['type'])

for i in sorted(ENABLED - {3}):
    require('Packet' + PACKETS[i] + 'Data')


def rust_type(versions):
    kind = versions[-1]['type']
    # Widen identifiers and temperature; normalize quantized G-force to f32.
    if len(versions) == 2 and versions[0]['type'] != kind:
        kind = 'f32' if 'f32' in [f['type'] for f in versions] else 'u16'
    for dim in reversed(versions[-1]['dims']):
        kind = f'[Option<{kind}>; MAX_CARS]' if dim in (22, 24) else f'[{kind}; {dim}]'
    return kind


def read_expr(field, versions):
    def inner(dims):
        if dims:
            expr = inner(dims[1:])
            closure = expr[:-1] if expr.endswith('?') else f'Ok({expr})'
            if dims[0] in (22, 24):
                return f'r.cars({dims[0]}, |r| {closure})?'
            return f'r.array(|r| {closure})?'
        kind = field['type']
        value = f'r.{kind}()?' if kind in PRIMITIVES else f'{kind}::read(r, format)?'
        target = rust_type([dict(f, dims=[]) for f in versions])
        if target != kind:
            value = f'{value} as {target}'
        if kind == 'i16' and target == 'f32':
            value = f'{value} / 1000.0'
        return value
    return inner(field['dims'])


out = ['// @generated by tools/telemetry/generate_parser.py; edit packet_tables.json instead.',
       'use super::{Reader, ParseError, MAX_CARS};']
for kind in sorted(needed):
    merged = fields(kind)
    out += ['#[derive(Debug, Clone, PartialEq)]', f'pub struct {kind} {{']
    for name, versions in merged.items():
        optional = len(versions) == 1 and kind in TABLES['2025'] and kind in TABLES['2026']
        typ = rust_type(versions)
        out.append(f'    pub {name}: ' + (f'Option<{typ}>' if optional else typ) + ',')
    same_layout = (kind not in TABLES['2025'] or kind not in TABLES['2026']
                   or TABLES['2025'][kind] == TABLES['2026'][kind])
    out += ['}', f'impl {kind} {{', '    pub(super) fn read(r: &mut Reader<\'_>, format: u16) -> Result<Self, ParseError> {',
            '        let _ = format;']
    if not same_layout:
        out.append('        if format == 2025 {')
    for index, fmt in enumerate(['2025'] if same_layout else ['2025', '2026']):
        if index:
            out.append('        } else {')
        out.append('            Ok(Self {')
        present = set()
        for field in TABLES[fmt].get(kind, TABLES['2026'].get(kind, [])):
            name = field['name']
            if name == 'header':
                continue
            present.add(name)
            versions = merged[name]
            expr = read_expr(field, versions)
            optional = len(versions) == 1 and kind in TABLES['2025'] and kind in TABLES['2026']
            out.append(f'                {name}: ' + (f'Some({expr})' if optional else expr) + ',')
        for name in (n for n in merged if n not in present):
            out.append(f'                {name}: None,')
        out.append('            })')
    if not same_layout:
        out.append('        }')
    out += ['    }', '}']
out += ['#[derive(Debug, Clone, PartialEq)]', 'pub enum Packet {']
for i in sorted(ENABLED):
    typ = 'super::Event' if i == 3 else 'Packet' + PACKETS[i] + 'Data'
    out.append(f'    {PACKETS[i]}(Box<{typ}>),')
out += ['}', 'pub(super) fn packet_size(format: u16, id: u8) -> Option<usize> {', '    match (format, id) {']
for fmt, schema in TABLES.items():
    for i in sorted(ENABLED):
        kind = 'Packet' + PACKETS[i] + 'Data'
        if kind in schema:
            n = size(kind, [], schema)
            out.append(f'        ({fmt}, {i}) => Some({n}),')
out += ['        _ => None,', '    }', '}', 'pub(super) fn read_packet(r: &mut Reader<\'_>, format: u16, id: u8) -> Result<Packet, ParseError> {', '    Ok(match id {']
for i in sorted(ENABLED):
    kind = 'super::Event' if i == 3 else 'Packet' + PACKETS[i] + 'Data'
    out.append(f'        {i} => Packet::{PACKETS[i]}(Box::new({kind}::read(r, format)?)),')
out += ['        _ => return Err(ParseError::UnsupportedPacketId { format, id }),', '    })', '}']
path = ROOT / 'crates/collector/src/telemetry/generated.rs'
path.write_text('\n'.join(out) + '\n')
subprocess.run(['rustfmt', '--edition', '2024', str(path)], check=True)
