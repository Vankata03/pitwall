#!/usr/bin/env python3
"""Regenerate dependency attribution and licence texts for the Windows release target.
Run after `pnpm install --frozen-lockfile` and `cargo fetch --locked`.
The authored track and font notices before `## Dependencies` are preserved.
"""
import json
import pathlib
import subprocess
import sys
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parents[2]
TARGETS = ('x86_64-pc-windows-msvc',)
packages = {}
for target in TARGETS:
    metadata = json.loads(subprocess.check_output([
        'cargo', 'metadata', '--locked', '--offline', '--format-version=1', '--filter-platform', target
    ], cwd=ROOT))
    nodes = {n['id']: n for n in metadata['resolve']['nodes']}
    by_id = {p['id']: p for p in metadata['packages']}
    seen = set()
    def visit(key):
        if key in seen:
            return
        seen.add(key)
        p = by_id[key]
        if key not in metadata['workspace_members']:
            packages[(p['name'], p['version'])] = (p['license'] or 'See licence files', pathlib.Path(p['manifest_path']).parent)
        for dep in nodes[key]['deps']:
            if any(k['kind'] != 'dev' for k in dep['dep_kinds']):
                visit(dep['pkg'])
    for key in metadata['workspace_members']:
        visit(key)

# Resolve installed production JS dependencies using Node's directory search.
def js_package(name, parent):
    for base in (parent, *parent.parents):
        candidate = base / 'node_modules' / name / 'package.json'
        if candidate.is_file():
            return candidate.resolve()
    raise RuntimeError(f'Missing installed dependency {name} from {parent}')

js_seen = set()
def visit_js(manifest):
    data = json.loads(manifest.read_text(encoding='utf-8'))
    key = (data['name'], data.get('version', 'workspace'))
    if key in js_seen:
        return
    js_seen.add(key)
    if data.get('version'):
        packages[key] = (data.get('license', 'See licence files'), manifest.parent)
    for name in data.get('dependencies', {}):
        visit_js(js_package(name, manifest.parent))
visit_js(ROOT / 'dashboard/package.json')

out = ['## Dependencies', '', 'Generated by `python3 tools/notices/generate.py` from locked production and build dependencies',
       'for Windows x64, plus the dashboard production dependencies.', '',
       '| Dependency | Version | Declared licence |', '| --- | --- | --- |']
for (name, version), (licence, _) in sorted(packages.items()):
    if name == '@pitwall/dashboard':
        continue
    out.append(f'| {name} | {version} | {licence} |')
for (name, version), (_, directory) in sorted(packages.items()):
    if name == '@pitwall/dashboard':
        continue
    files = [p for p in directory.iterdir() if p.is_file() and p.name.lower().startswith(('license', 'licence', 'copying', 'copyright', 'unlicense'))]
    for folder in ('LICENSES', 'licenses'):
        if (directory / folder).is_dir():
            files.extend(p for p in (directory / folder).rglob('*') if p.is_file())
    if not files:
        # Some crates omit workspace-level licence files from their published archive.
        cache = ROOT / 'tools/notices/upstream' / f'{name}-{version}.txt'
        if not cache.is_file() and '--fetch-missing' in sys.argv:
            data = json.loads((directory / '.cargo_vcs_info.json').read_text(encoding='utf-8'))
            import tomllib
            package = tomllib.loads((directory / 'Cargo.toml').read_text(encoding='utf-8'))['package']
            repository = package.get('repository', package.get('homepage', '')).split('/tree/')[0].removesuffix('.git')
            revision = data['git']['sha1']
            if repository.startswith('https://github.com/'):
                raw = repository.replace('https://github.com/', 'https://raw.githubusercontent.com/') + '/' + revision
            elif repository.startswith('https://gitlab.redox-os.org/'):
                raw = repository + '/-/raw/' + revision
            else:
                raise RuntimeError(f'Unsupported upstream: {repository}')
            for filename in ('LICENSE-MIT.txt', 'LICENSE-MIT', 'LICENSE', 'LICENSE.txt', 'LICENSE.md', 'COPYING'):
                url = raw + '/' + filename
                try:
                    text = urllib.request.urlopen(url).read().decode()
                except urllib.error.HTTPError as error:
                    if error.code == 404:
                        continue
                    raise
                cache.parent.mkdir(parents=True, exist_ok=True)
                cache.write_text(f'Source: {url}\n\n{text}', encoding='utf-8')
                break
        if not cache.is_file():
            raise RuntimeError(f'No licence text found for {name} {version}; rerun with --fetch-missing')
        files = [cache]
    out += ['', f'### {name} {version}']
    for path in sorted(set(files)):
        out += ['', f'`{path.name}`', '', '````text', path.read_text(encoding='utf-8').rstrip(), '````']
notice = ROOT / 'THIRD-PARTY-NOTICES.md'
notice.write_text(notice.read_text(encoding='utf-8').split('## Dependencies')[0] + '\n'.join(out) + '\n', encoding='utf-8')
