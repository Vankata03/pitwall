//! The field table defines both little-endian encoding and the allocation-free TS decoder.
use crate::model::{Readout, Reference, Regulations, SessionModel};
pub const FRAME_SIZE: usize = 976;
macro_rules! fields {
    ($($name:ident, $offset:literal, $ty:ty, $getter:literal;)+) => {
        #[allow(non_snake_case)]
        #[derive(Default)]
        struct Car { $($name: $ty,)+ }
        impl Car {
            fn write(&self, bytes: &mut [u8]) { $(bytes[$offset..$offset + size_of::<$ty>()].copy_from_slice(&self.$name.to_le_bytes());)+ }
        }
        pub fn decoder() -> String {
            let mut s = String::from("// @generated by wire::frame; do not edit.\nexport const FRAME_SIZE = 976;\nexport class Frame {\n  readonly view: DataView;\n  constructor(buffer: ArrayBuffer) { if (buffer.byteLength !== FRAME_SIZE) throw new Error('Invalid Frame size'); this.view = new DataView(buffer); }\n  get epoch() { return this.view.getUint32(0, true); }\n  get seq() { return this.view.getUint32(4, true); }\n  get sessionTime() { return this.view.getFloat64(8, true); }\n");
            $(s.push_str(&format!("  {}(car: number): number {{ return this.view.{}(16 + car * 40 + {}{}); }}\n", stringify!($name), $getter, $offset, if size_of::<$ty>() > 1 { ", true" } else { "" }));)+
            s.push_str("}\n"); s
        }
    }
}
fields! {
 speed, 0, u16, "getUint16";
 gear, 2, i8, "getInt8";
 throttle, 3, u8, "getUint8";
 brake, 4, u8, "getUint8";
 steering, 5, i8, "getInt8";
 rpm, 6, u16, "getUint16";
 worldX, 8, f32, "getFloat32";
 worldZ, 12, f32, "getFloat32";
 lapDistance, 16, f32, "getFloat32";
 currentLapTime, 20, u32, "getUint32";
 deltaBest, 24, i32, "getInt32";
 deltaPrevious, 28, i32, "getInt32";
 gLateral, 32, i16, "getInt16";
 gLongitudinal, 34, i16, "getInt16";
 ersPercent, 36, u8, "getUint8";
 aeroState, 37, u8, "getUint8";
 readout, 38, u16, "getUint16";
}
fn unpack<T>(r: Readout<T>) -> (u16, Option<T>) {
    match r {
        Readout::Live(v) => (0, Some(v)),
        Readout::Stale(v) => (1, Some(v)),
        Readout::Restricted => (2, None),
        Readout::Absent => (3, None),
    }
}
#[allow(non_snake_case)]
pub fn encode(model: &SessionModel, epoch: u32, seq: u32) -> Vec<u8> {
    let mut bytes = vec![0; FRAME_SIZE];
    bytes[..4].copy_from_slice(&epoch.to_le_bytes());
    bytes[4..8].copy_from_slice(&seq.to_le_bytes());
    bytes[8..16].copy_from_slice(&(model.session_time() as f64).to_le_bytes());
    for index in 0..24 {
        let mut c = Car {
            readout: 0x3fff,
            ..Default::default()
        };
        if let Some(car) = model.car(index) {
            let (t, tv) = unpack(car.telemetry());
            let (m, mv) = unpack(car.motion());
            let (l, lv) = unpack(car.lap());
            let (s, sv) = unpack(car.ers_percentage());
            let (b, bv) = unpack(car.live_delta(Reference::Best));
            let (p, pv) = unpack(car.live_delta(Reference::Previous));
            let (a, av) = if car.regulations() == Some(Regulations::Pre2026) {
                unpack(car.telemetry().map(|v| v.drs))
            } else {
                unpack(car.aero().map(|v| v.active_aero_mode))
            };
            c.readout = t | (m << 2) | (l << 4) | (s << 6) | (b << 8) | (p << 10) | (a << 12);
            if let Some(v) = tv {
                c.speed = v.speed;
                c.gear = v.gear;
                c.throttle = (v.throttle * 100.).round() as u8;
                c.brake = (v.brake * 100.).round() as u8;
                c.steering = (v.steer * 100.).round() as i8;
                c.rpm = v.engine_rpm;
            }
            if let Some(v) = mv {
                c.worldX = v.world_position_x;
                c.worldZ = v.world_position_z;
                c.gLateral = (v.g_force_lateral * 1000.).round() as i16;
                c.gLongitudinal = (v.g_force_longitudinal * 1000.).round() as i16;
            }
            if let Some(v) = lv {
                c.lapDistance = v.lap_distance;
                c.currentLapTime = v.current_lap_time_in_ms;
            }
            c.deltaBest = bv.unwrap_or(0.).round() as i32;
            c.deltaPrevious = pv.unwrap_or(0.).round() as i32;
            c.ersPercent = sv.unwrap_or(0.).round().clamp(0., 100.) as u8;
            c.aeroState = av.unwrap_or(0);
        }
        c.write(&mut bytes[16 + index * 40..16 + (index + 1) * 40]);
    }
    bytes
}
